quint32 readGitBigEndian32(const char* bytes)
{
    const auto* value = reinterpret_cast<const unsigned char*>(bytes);
    return (static_cast<quint32>(value[0]) << 24)
        | (static_cast<quint32>(value[1]) << 16)
        | (static_cast<quint32>(value[2]) << 8)
        | static_cast<quint32>(value[3]);
}

quint16 readGitBigEndian16(const char* bytes)
{
    const auto* value = reinterpret_cast<const unsigned char*>(bytes);
    return static_cast<quint16>((static_cast<quint16>(value[0]) << 8) | value[1]);
}

QString findGitRoot(const QString& startPath)
{
    QDir directory(startPath);
    if (!directory.exists())
        return QString();
    while (true) {
        const QString dotGit = directory.filePath(QStringLiteral(".git"));
        if (QFileInfo::exists(dotGit))
            return directory.absolutePath();
        // Stop at the filesystem root.  Comparing absoluteFilePath("..")
        // with absolutePath() never matches ("/.." != "/") and previously
        // looped forever when the project had no .git, freezing the UI thread
        // as soon as the Git pane was opened.
        if (directory.absolutePath() == QDir::rootPath())
            break;
        if (!directory.cdUp())
            break;
    }
    return QString();
}

QString nativeGitStatus(const QString& startPath)
{
    const QString root = findGitRoot(startPath);
    if (root.isEmpty())
        return QString();

    const QString dotGit = QDir(root).filePath(QStringLiteral(".git"));
    QFileInfo dotGitInfo(dotGit);
    if (!dotGitInfo.isDir())
        return QStringLiteral("HarmonyOS 原生状态读取器暂不支持 Git worktree 元数据。");

    QString branch = QStringLiteral("HEAD");
    QFile head(QDir(dotGit).filePath(QStringLiteral("HEAD")));
    if (head.open(QIODevice::ReadOnly | QIODevice::Text)) {
        const QString headText = QString::fromUtf8(head.readAll()).trimmed();
        if (headText.startsWith(QStringLiteral("ref: refs/heads/")))
            branch = headText.mid(QStringLiteral("ref: refs/heads/").size());
        else if (!headText.isEmpty())
            branch = QStringLiteral("（分离的 HEAD）");
    }

    QFile index(QDir(dotGit).filePath(QStringLiteral("index")));
    if (!index.open(QIODevice::ReadOnly))
        return QStringLiteral("位于分支 %1\nGit 索引尚未生成。").arg(branch);
    const QByteArray bytes = index.readAll();
    if (bytes.size() < 12 || bytes.left(4) != QByteArrayLiteral("DIRC"))
        return QStringLiteral("位于分支 %1\n不支持当前 Git 索引格式。").arg(branch);
    const quint32 version = readGitBigEndian32(bytes.constData() + 4);
    if (version != 2 && version != 3)
        return QStringLiteral("位于分支 %1\n不支持 Git 索引版本 %2。").arg(branch).arg(version);

    const quint32 entryCount = readGitBigEndian32(bytes.constData() + 8);
    int offset = 12;
    QHash<QString, bool> tracked;
    QStringList changes;
    for (quint32 entry = 0; entry < entryCount && offset + 62 <= bytes.size(); ++entry) {
        const char* record = bytes.constData() + offset;
        const quint16 flags = readGitBigEndian16(record + 60);
        int pathLength = flags & 0x0fff;
        if (pathLength == 0x0fff)
            pathLength = 0;
        int actualPathLength = pathLength;
        if (actualPathLength == 0) {
            while (offset + 62 + actualPathLength < bytes.size()
                   && bytes.at(offset + 62 + actualPathLength) != '\0')
                ++actualPathLength;
        }
        if (offset + 62 + actualPathLength >= bytes.size())
            break;
        const QString relativePath = QString::fromUtf8(bytes.constData() + offset + 62, actualPathLength);
        tracked.insert(relativePath, true);
        const QString absolutePath = QDir(root).filePath(relativePath);
        QFileInfo fileInfo(absolutePath);
        if (!fileInfo.exists()) {
            changes.append(QStringLiteral(" D  %1").arg(relativePath));
        } else {
            QFile file(absolutePath);
            QByteArray content;
            if (file.open(QIODevice::ReadOnly))
                content = file.readAll();
            const QByteArray header = QByteArrayLiteral("blob ")
                + QByteArray::number(content.size()) + QByteArrayLiteral("\0");
            const QByteArray blobHash = QCryptographicHash::hash(header + content, QCryptographicHash::Sha1);
            const QByteArray indexHash(record + 40, 20);
            if (blobHash != indexHash)
                changes.append(QStringLiteral(" M  %1").arg(relativePath));
        }
        const int recordSize = 62 + actualPathLength + 1;
        offset += (recordSize + 7) & ~7;
    }

    QDirIterator iterator(root, QDir::Files | QDir::Hidden | QDir::NoSymLinks,
                          QDirIterator::Subdirectories);
    while (iterator.hasNext()) {
        const QString absolutePath = iterator.next();
        if (absolutePath == dotGit || absolutePath.startsWith(dotGit + QDir::separator()))
            continue;
        const QString relativePath = QDir(root).relativeFilePath(absolutePath);
        if (!tracked.contains(relativePath))
            changes.append(QStringLiteral("??  %1").arg(relativePath));
    }

    QString result = QStringLiteral("位于分支 %1\n").arg(branch);
    if (changes.isEmpty())
        result += QStringLiteral("没有待提交的更改，工作区干净");
    else
        result += changes.join(QLatin1Char('\n'));
    return result;
}

