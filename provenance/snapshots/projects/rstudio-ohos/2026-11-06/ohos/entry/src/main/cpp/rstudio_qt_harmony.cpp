    void startTerminal()
    {
        if (terminalProcess_ && terminalProcess_->state() == QProcess::Running)
            return;
        if (terminalProcess_) {
            terminalProcess_->deleteLater();
            terminalProcess_ = nullptr;
        }
        terminalProcess_ = new QProcess(this);
        terminalProcess_->setWorkingDirectory(projectPath_);
        terminalProcess_->setProcessChannelMode(QProcess::MergedChannels);
        connect(terminalProcess_, &QProcess::readyRead, this, &RStudioMainWindow::appendTerminalOutput);
        connect(terminalProcess_, &QProcess::started, this, [this]() {
            qInfo().noquote() << "RStudioQt terminal started" << shellProgram()
                              << "cwd=" << projectPath_;
            terminalOutput_->appendPlainText(QStringLiteral("终端已就绪（%1）").arg(shellProgram()));
            statusBar()->showMessage(QStringLiteral("终端已就绪"), 3000);
        });
        connect(terminalProcess_, &QProcess::errorOccurred, this, [this](QProcess::ProcessError error) {
            const QString detail = error == QProcess::FailedToStart
                ? QStringLiteral("当前 HarmonyOS 运行时无法使用终端。")
                : QStringLiteral("终端意外停止。");
            terminalOutput_->appendPlainText(detail);
            statusBar()->showMessage(detail, 5000);
            qWarning().noquote() << "RStudioQt terminal error" << static_cast<int>(error) << detail;
        });
        qInfo().noquote() << "RStudioQt terminal launch" << shellProgram()
                          << "cwd=" << projectPath_;
        // Without a pty, `sh -i` prints "can't find tty fd" and disables job
        // control.  Run a normal pipe-backed shell instead; the pane renders
        // its own "$ command" prompt.
        terminalProcess_->start(shellProgram(), QStringList());
        terminalOutput_->appendPlainText(QStringLiteral("%1  %2").arg(shellProgram(), projectPath_));
    }

