    void createMenus()
    {
        // HarmonyOS PC reserves the top strip of a full-screen window for the
        // system window drag gesture, so pointer events never reach a native
        // menu bar there. Hide the native bar and host a second QMenuBar in a
        // toolbar below the reserved strip; menu items and their popups then
        // receive normal mouse input.
        menuBar()->hide();
        auto* menuToolbar = addToolBar(QStringLiteral("菜单"));
        menuToolbar->setObjectName(QStringLiteral("menu_toolbar"));
        menuToolbar->setMovable(false);
        menuToolbar->setFloatable(false);
        auto* menuContainer = new QWidget(menuToolbar);
        auto* menuLayout = new QVBoxLayout(menuContainer);
        menuLayout->setContentsMargins(0, 0, 0, 0);
        menuLayout->setSpacing(0);

        auto* reservedStrip = new QWidget(menuContainer);
        reservedStrip->setObjectName(QStringLiteral("reserved_top_strip"));
        reservedStrip->setFixedHeight(76);
        auto* stripLayout = new QHBoxLayout(reservedStrip);
        stripLayout->setContentsMargins(16, 0, 16, 0);
        stripLayout->setSpacing(10);

        auto* brandMark = new QLabel(QStringLiteral("R"), reservedStrip);
        brandMark->setObjectName(QStringLiteral("brandMark"));
        brandMark->setFixedSize(48, 48);
        brandMark->setAlignment(Qt::AlignCenter);
        stripLayout->addWidget(brandMark);

        auto* brandText = new QWidget(reservedStrip);
        auto* brandTextLayout = new QVBoxLayout(brandText);
        brandTextLayout->setContentsMargins(0, 0, 0, 0);
        brandTextLayout->setSpacing(0);
        auto* brandTitle = new QLabel(QStringLiteral("RStudio 鸿蒙版"), brandText);
        brandTitle->setObjectName(QStringLiteral("brandTitle"));
        auto* brandSubtitle = new QLabel(QStringLiteral("原生 R 工作台"), brandText);
        brandSubtitle->setObjectName(QStringLiteral("brandSubtitle"));
        brandTextLayout->addWidget(brandTitle);
        brandTextLayout->addWidget(brandSubtitle);
        stripLayout->addWidget(brandText);
        stripLayout->addStretch(1);

        sessionLabel_ = new QLabel(QStringLiteral("○ 正在启动内置 R…"), reservedStrip);
        sessionLabel_->setObjectName(QStringLiteral("status_pill"));
        sessionLabel_->setProperty("online", false);

        auto* headerCommand = new QLineEdit(reservedStrip);
        headerCommand->setObjectName(QStringLiteral("header_r_command"));
        headerCommand->setPlaceholderText(QStringLiteral("输入 R 命令，回车运行"));
        headerCommand->setMinimumWidth(640);
        headerCommand->setMaximumWidth(1000);
        headerCommand->setClearButtonEnabled(true);
        connect(headerCommand, &QLineEdit::returnPressed, this, [this, headerCommand]() {
            const QString command = headerCommand->text().trimmed();
            if (command.isEmpty())
                return;
            headerCommand->clear();
            executeR(command);
        });
        stripLayout->addWidget(headerCommand, 3);

        auto* headerRunButton = new QPushButton(QStringLiteral("运行"), reservedStrip);
        headerRunButton->setObjectName(QStringLiteral("header_r_run"));
        headerRunButton->setProperty("variant", QStringLiteral("primary"));
        headerRunButton->setMinimumWidth(64);
        connect(headerRunButton, &QPushButton::clicked, this, [this, headerCommand]() {
            const QString command = headerCommand->text().trimmed();
            if (command.isEmpty())
                return;
            headerCommand->clear();
            executeR(command);
        });
        stripLayout->addWidget(headerRunButton);

        sessionButton_ = new QPushButton(QStringLiteral("网页会话"), reservedStrip);
        sessionButton_->setProperty("variant", QStringLiteral("ghost"));
        sessionButton_->setVisible(false);
        connect(sessionButton_, &QPushButton::clicked, this, &RStudioMainWindow::openSessionUrl);
        stripLayout->addWidget(sessionButton_);
        stripLayout->addWidget(sessionLabel_);

        menuLayout->addWidget(reservedStrip);
        menuBarWidget_ = new QMenuBar(menuContainer);
        menuBarWidget_->setObjectName(QStringLiteral("app_menubar"));
        menuLayout->addWidget(menuBarWidget_);
        menuToolbar->addWidget(menuContainer);

        QMenu* file = menuBarWidget_->addMenu(QStringLiteral("文件"));
        file->addAction(QStringLiteral("新建文件"), this, &RStudioMainWindow::newFile, QKeySequence::New);
        file->addAction(QStringLiteral("打开文件…"), this, &RStudioMainWindow::openFile, QKeySequence::Open);
        file->addAction(QStringLiteral("保存"), this, &RStudioMainWindow::saveFile, QKeySequence::Save);
        file->addAction(QStringLiteral("另存为…"), this, &RStudioMainWindow::saveFileAs, QKeySequence::SaveAs);
        file->addSeparator();
        QAction* closeTabAction = file->addAction(QStringLiteral("关闭标签"));
        closeTabAction->setShortcut(QKeySequence::Close);
        connect(closeTabAction, &QAction::triggered, this, [this]() {
            if (sourceTabs_)
                closeSourceTab(sourceTabs_->currentIndex());
        });
        file->addSeparator();
        file->addAction(QStringLiteral("退出"), this, &QWidget::close, QKeySequence::Quit);

        QMenu* code = menuBarWidget_->addMenu(QStringLiteral("代码"));
        code->addAction(QStringLiteral("运行当前行/选区"), this, &RStudioMainWindow::runSelection,
                        QKeySequence(Qt::CTRL | Qt::Key_Return));
        code->addAction(QStringLiteral("运行整个文件"), this, &RStudioMainWindow::runEntireFile);
        code->addSeparator();
        code->addAction(QStringLiteral("查找…"), this, &RStudioMainWindow::showFindDialog, QKeySequence::Find);
        code->addAction(QStringLiteral("替换…"), this, &RStudioMainWindow::showFindDialog, QKeySequence::Replace);
        code->addSeparator();
        code->addAction(QStringLiteral("清空控制台"), this, &RStudioMainWindow::clearConsole,
                        QKeySequence(Qt::CTRL | Qt::Key_L));

        QMenu* view = menuBarWidget_->addMenu(QStringLiteral("视图"));
        const auto addPaneAction = [this, view](const QString& name, QWidget* pane) {
            if (!pane)
                return;
            QAction* action = view->addAction(name);
            connect(action, &QAction::triggered, this, [this, pane]() {
                if (sideTabs_)
                    sideTabs_->setCurrentWidget(pane);
            });
        };
        addPaneAction(QStringLiteral("环境"), environmentPane_);
        addPaneAction(QStringLiteral("历史"), sideTabs_ ? sideTabs_->widget(1) : nullptr);
        addPaneAction(QStringLiteral("数据"), dataPane_);
        addPaneAction(QStringLiteral("文件"), filesPane_);
        addPaneAction(QStringLiteral("程序包"), packagesPane_);
        addPaneAction(QStringLiteral("绘图"), plotsPane_);
        addPaneAction(QStringLiteral("帮助"), helpPane_);
        addPaneAction(QStringLiteral("终端"), terminalPane_);
        addPaneAction(QStringLiteral("版本控制"), gitPane_);

        QMenu* session = menuBarWidget_->addMenu(QStringLiteral("会话"));
        session->addAction(QStringLiteral("刷新环境"), this, &RStudioMainWindow::refreshEnvironment);
        session->addAction(QStringLiteral("选择项目…"), this, &RStudioMainWindow::setProjectFromDialog);
        session->addAction(QStringLiteral("打开已有会话"), this, &RStudioMainWindow::openSessionUrl);

        QMenu* help = menuBarWidget_->addMenu(QStringLiteral("帮助"));
        help->addAction(QStringLiteral("运行自检…"), this, &RStudioMainWindow::runSelfTest);
        help->addAction(QStringLiteral("关于 RStudio 鸿蒙版"), this, &RStudioMainWindow::showAbout);
    }

