class RStudioSyntaxHighlighter : public QSyntaxHighlighter
{
public:
    explicit RStudioSyntaxHighlighter(QTextDocument* document)
        : QSyntaxHighlighter(document)
    {
        commentFormat_.setForeground(QColor(QStringLiteral("#7e9b88")));
        stringFormat_.setForeground(QColor(QStringLiteral("#e4b27c")));
        keywordFormat_.setForeground(QColor(QStringLiteral("#78b9ff")));
        keywordFormat_.setFontWeight(QFont::Bold);
        numberFormat_.setForeground(QColor(QStringLiteral("#a8d48a")));
    }

protected:
    void highlightBlock(const QString& text) override
    {
        highlightMatches(text, QRegularExpression(QStringLiteral("#[^\\n]*")), commentFormat_);
        highlightMatches(text, QRegularExpression(QStringLiteral("'([^'\\\\]|\\\\.)*'|\"([^\"\\\\]|\\\\.)*\"")), stringFormat_);
        highlightMatches(text,
                         QRegularExpression(QStringLiteral("\\b(function|if|else|for|while|repeat|in|next|break|library|require|return|TRUE|FALSE|NULL|NA)\\b")),
                         keywordFormat_);
        highlightMatches(text, QRegularExpression(QStringLiteral("\\b[0-9]+(\\.[0-9]+)?\\b")), numberFormat_);
    }

private:
    void highlightMatches(const QString& text, const QRegularExpression& expression,
                          const QTextCharFormat& format)
    {
        QRegularExpressionMatchIterator iterator = expression.globalMatch(text);
        while (iterator.hasNext()) {
            const QRegularExpressionMatch match = iterator.next();
            setFormat(match.capturedStart(), match.capturedLength(), format);
        }
    }

    QTextCharFormat commentFormat_;
    QTextCharFormat stringFormat_;
    QTextCharFormat keywordFormat_;
    QTextCharFormat numberFormat_;
};

