    void createFileInProject()
    {
        QString name;
        if (!promptForText(QStringLiteral("新建文件"),
                           QStringLiteral("文件名（例如 analysis.R）："),
                           QStringLiteral("script.R"), &name))
            return;
        const QString trimmed = name.trimmed();
        if (trimmed.isEmpty())
            return;
        if (trimmed.contains(QLatin1Char('/')) || trimmed.contains(QLatin1Char('\\'))) {
            showWarningMessage(QStringLiteral("新建文件"),
                               QStringLiteral("文件名不能包含目录分隔符。"));
            return;
        }
        const QString path = QDir(projectPath_).filePath(trimmed);
        if (QFileInfo::exists(path)) {
            showWarningMessage(QStringLiteral("新建文件"),
                               QStringLiteral("文件已存在：\n%1").arg(path));
            return;
        }
        QFile file(path);
        if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
            showWarningMessage(QStringLiteral("新建文件"), file.errorString());
            return;
        }
        file.close();
        refreshFilesPane();
        openFilePath(path);
    }

    void createFolderInProject()
    {
        QString name;
        if (!promptForText(QStringLiteral("新建文件夹"),
                           QStringLiteral("文件夹名称："),
                           QString(), &name))
            return;
        const QString trimmed = name.trimmed();
        if (trimmed.isEmpty())
            return;
        if (trimmed.contains(QLatin1Char('/')) || trimmed.contains(QLatin1Char('\\'))) {
            showWarningMessage(QStringLiteral("新建文件夹"),
                               QStringLiteral("文件夹名称不能包含目录分隔符。"));
            return;
        }
        const QString path = QDir(projectPath_).filePath(trimmed);
        if (!QDir().mkpath(path)) {
            showWarningMessage(QStringLiteral("新建文件夹"),
                               QStringLiteral("无法创建文件夹：\n%1").arg(path));
            return;
        }
        refreshFilesPane();
        statusBar()->showMessage(QStringLiteral("已创建文件夹：%1").arg(path), 3000);
    }

    void deleteSelectedFile()
    {
        if (!files_)
            return;
        const QModelIndex index = files_->currentIndex();
        if (!index.isValid()) {
            statusBar()->showMessage(QStringLiteral("请先选择要删除的文件或文件夹"), 3000);
            return;
        }
        const QString path = fileModel_->filePath(index);
        const QFileInfo info(path);
        if (!info.exists())
            return;
        if (!confirmDelete(path))
            return;
        const bool removed = info.isDir() ? QDir(path).removeRecursively() : QFile::remove(path);
        if (!removed) {
            showWarningMessage(QStringLiteral("删除失败"),
                               QStringLiteral("无法删除：\n%1").arg(path));
            return;
        }
        refreshFilesPane();
        statusBar()->showMessage(QStringLiteral("已删除：%1").arg(path), 3000);
    }

    void refreshFilesPane()
    {
        if (!fileModel_ || !files_)
            return;
        // QFileSystemModel caches size/mtime and the HarmonyOS file watcher
        // does not always report editor writes.  Reset the root so a save is
        // reflected in the Files pane immediately.
        fileModel_->setRootPath(QString());
        files_->setRootIndex(fileModel_->setRootPath(projectPath_));
        statusBar()->showMessage(QStringLiteral("文件列表已刷新"), 2000);
    }

