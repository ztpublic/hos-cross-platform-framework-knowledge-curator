class RStudioSourceEditor : public QPlainTextEdit
{
public:
    explicit RStudioSourceEditor(QWidget* parent = nullptr)
        : QPlainTextEdit(parent)
    {
        setObjectName(QStringLiteral("source_editor"));
        setLineWrapMode(QPlainTextEdit::NoWrap);
        setFont(applicationMonospaceFont());
        setPlaceholderText(QStringLiteral("打开 R、Rmd、qmd 或文本文件…"));
        lineNumberArea_ = new RStudioLineNumberArea(this);
        connect(this, &QPlainTextEdit::blockCountChanged, this,
                [this](int) { updateLineNumberAreaWidth(); });
        connect(this, &QPlainTextEdit::updateRequest, this,
                &RStudioSourceEditor::updateLineNumberArea);
        updateLineNumberAreaWidth();
    }

    int lineNumberAreaWidth() const
    {
        int digits = 1;
        int maximum = qMax(1, blockCount());
        while (maximum >= 10) {
            maximum /= 10;
            ++digits;
        }
        return 12 + fontMetrics().horizontalAdvance(QLatin1Char('9')) * digits;
    }

    void lineNumberAreaPaintEvent(QPaintEvent* event)
    {
        QPainter painter(lineNumberArea_);
        painter.fillRect(event->rect(), QColor(QStringLiteral("#0b141c")));
        painter.setPen(QColor(QStringLiteral("#172633")));
        painter.drawLine(lineNumberArea_->width() - 1, event->rect().top(),
                         lineNumberArea_->width() - 1, event->rect().bottom());
        const int currentBlock = textCursor().block().blockNumber();
        QTextBlock block = firstVisibleBlock();
        int blockNumber = block.blockNumber();
        int top = qRound(blockBoundingGeometry(block).translated(contentOffset()).top());
        int bottom = top + qRound(blockBoundingRect(block).height());
        while (block.isValid() && top <= event->rect().bottom()) {
            if (block.isVisible() && bottom >= event->rect().top()) {
                painter.setPen(blockNumber == currentBlock
                                   ? QColor(QStringLiteral("#3dd6c3"))
                                   : QColor(QStringLiteral("#5a7185")));
                painter.drawText(0, top, lineNumberArea_->width() - 7,
                                 fontMetrics().height(), Qt::AlignRight,
                                 QString::number(blockNumber + 1));
            }
            block = block.next();
            top = bottom;
            bottom = top + qRound(blockBoundingRect(block).height());
            ++blockNumber;
        }
    }

protected:
    void resizeEvent(QResizeEvent* event) override
    {
        QPlainTextEdit::resizeEvent(event);
        const QRect contents = contentsRect();
        lineNumberArea_->setGeometry(
            QRect(contents.left(), contents.top(), lineNumberAreaWidth(), contents.height()));
    }

private:
    void updateLineNumberAreaWidth()
    {
        setViewportMargins(lineNumberAreaWidth(), 0, 0, 0);
    }

    void updateLineNumberArea(const QRect& rect, int dy)
    {
        if (dy)
            lineNumberArea_->scroll(0, dy);
        else
            lineNumberArea_->update(0, rect.y(), lineNumberArea_->width(), rect.height());
        if (rect.contains(viewport()->rect()))
            updateLineNumberAreaWidth();
    }

    QWidget* lineNumberArea_ = nullptr;
};

