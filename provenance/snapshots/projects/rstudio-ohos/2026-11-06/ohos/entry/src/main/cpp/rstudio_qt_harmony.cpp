protected:
    void closeEvent(QCloseEvent* event) override
    {
        bool hasUnsavedSource = false;
        for (int index = 0; index < sourceTabs_->count(); ++index) {
            auto* sourceEditor = qobject_cast<QPlainTextEdit*>(sourceTabs_->widget(index));
            if (sourceEditor && sourceEditor->document()->isModified()) {
                hasUnsavedSource = true;
                break;
            }
        }

        if (hasUnsavedSource) {
            const SaveChangesChoice choice = askSaveChanges(
                QStringLiteral("关闭前要保存已修改的源文件吗？"));
            if (choice == SaveChangesChoice::Cancel) {
                event->ignore();
                return;
            }
            if (choice == SaveChangesChoice::Save) {
                const int previousIndex = sourceTabs_->currentIndex();
                for (int index = 0; index < sourceTabs_->count(); ++index) {
                    auto* sourceEditor = qobject_cast<QPlainTextEdit*>(sourceTabs_->widget(index));
                    if (!sourceEditor || !sourceEditor->document()->isModified())
                        continue;
                    sourceTabs_->setCurrentIndex(index);
                    if (!saveFile()) {
                        sourceTabs_->setCurrentIndex(previousIndex);
                        event->ignore();
                        return;
                    }
                }
                sourceTabs_->setCurrentIndex(previousIndex);
            }
        }
        event->accept();
    }

    bool eventFilter(QObject* watched, QEvent* event) override
    {
        if (watched == consoleInput_ && event->type() == QEvent::KeyPress) {
            auto* key = static_cast<QKeyEvent*>(event);
            if (key->key() == Qt::Key_Up) {
                recallConsoleHistory(-1);
                return true;
            }
            if (key->key() == Qt::Key_Down) {
                recallConsoleHistory(1);
                return true;
            }
            if (key->key() == Qt::Key_L && key->modifiers().testFlag(Qt::ControlModifier)) {
                clearConsole();
                return true;
            }
        }
        return QMainWindow::eventFilter(watched, event);
    }

