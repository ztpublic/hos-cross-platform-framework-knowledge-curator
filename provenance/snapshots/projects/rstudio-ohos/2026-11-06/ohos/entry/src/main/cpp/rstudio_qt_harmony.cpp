    SaveChangesChoice askSaveChanges(const QString& message)
    {
        QMessageBox box(QMessageBox::Question, QStringLiteral("未保存的更改"), message,
                        QMessageBox::NoButton, this);
        QPushButton* save = box.addButton(QStringLiteral("保存"), QMessageBox::AcceptRole);
        box.addButton(QStringLiteral("不保存"), QMessageBox::DestructiveRole);
        QPushButton* cancel = box.addButton(QStringLiteral("取消"), QMessageBox::RejectRole);
        box.setDefaultButton(save);
        box.setEscapeButton(cancel);
        box.exec();
        if (box.clickedButton() == save)
            return SaveChangesChoice::Save;
        if (box.clickedButton() == cancel)
            return SaveChangesChoice::Cancel;
        return SaveChangesChoice::Discard;
    }

