    QTextDocument::FindFlags currentFindFlags(bool backward) const
    {
        QTextDocument::FindFlags flags;
        if (backward)
            flags |= QTextDocument::FindBackward;
        if (findCaseCheck_ && findCaseCheck_->isChecked())
            flags |= QTextDocument::FindCaseSensitively;
        if (findWholeCheck_ && findWholeCheck_->isChecked())
            flags |= QTextDocument::FindWholeWords;
        return flags;
    }

    void findInEditor(bool backward)
    {
        if (!findInput_ || !editor_)
            return;
        const QString needle = findInput_->text();
        if (needle.isEmpty())
            return;
        const QTextDocument::FindFlags flags = currentFindFlags(backward);
        QTextCursor found = editor_->document()->find(needle, editor_->textCursor(), flags);
        if (found.isNull()) {
            QTextCursor wrap(editor_->document());
            wrap.movePosition(backward ? QTextCursor::End : QTextCursor::Start);
            found = editor_->document()->find(needle, wrap, flags);
        }
        if (found.isNull()) {
            statusBar()->showMessage(QStringLiteral("未找到：%1").arg(needle), 3000);
            return;
        }
        editor_->setTextCursor(found);
        editor_->centerCursor();
        editor_->setFocus();
        statusBar()->showMessage(QStringLiteral("已找到：%1").arg(needle), 1500);
    }

    void replaceInEditor()
    {
        if (!findInput_ || !editor_)
            return;
        const QString needle = findInput_->text();
        if (needle.isEmpty())
            return;
        const QString replacement = replaceInput_ ? replaceInput_->text() : QString();
        QTextCursor cursor = editor_->textCursor();
        if (cursor.hasSelection()) {
            const Qt::CaseSensitivity sensitivity =
                (findCaseCheck_ && findCaseCheck_->isChecked())
                    ? Qt::CaseSensitive : Qt::CaseInsensitive;
            if (cursor.selectedText().compare(needle, sensitivity) == 0) {
                cursor.insertText(replacement);
                editor_->setTextCursor(cursor);
            }
        }
        findInEditor(false);
    }

    void replaceAllInEditor()
    {
        if (!findInput_ || !editor_)
            return;
        const QString needle = findInput_->text();
        if (needle.isEmpty())
            return;
        const QString replacement = replaceInput_ ? replaceInput_->text() : QString();
        const QTextDocument::FindFlags flags = currentFindFlags(false);
        QTextCursor cursor(editor_->document());
        cursor.beginEditBlock();
        int count = 0;
        QTextCursor found = editor_->document()->find(needle, cursor, flags);
        while (!found.isNull() && count < 10000) {
            found.insertText(replacement);
            ++count;
            found = editor_->document()->find(needle, found, flags);
        }
        cursor.endEditBlock();
        statusBar()->showMessage(QStringLiteral("已替换 %1 处").arg(count), 3000);
    }

    void populateDataTable(const QString& csvText)
    {
        const QString trimmed = csvText.trimmed();
        if (trimmed.isEmpty() || trimmed.startsWith(QStringLiteral("对象不存在"))) {
            dataTable_->clear();
            dataTable_->setRowCount(0);
            dataTable_->setColumnCount(0);
            return;
        }

        const QStringList lines = trimmed.split(QRegularExpression(QStringLiteral("[\\r\\n]+")), Qt::SkipEmptyParts);
        if (lines.isEmpty())
            return;

        const QStringList headers = parseCsvLine(lines.first());
        dataTable_->clear();
        dataTable_->setColumnCount(headers.size());
        dataTable_->setRowCount(std::max(0, lines.size() - 1));
        dataTable_->setHorizontalHeaderLabels(headers);
        for (int row = 1; row < lines.size(); ++row) {
            const QStringList values = parseCsvLine(lines.at(row));
            for (int column = 0; column < headers.size() && column < values.size(); ++column) {
                dataTable_->setItem(row - 1, column, new QTableWidgetItem(values.at(column)));
            }
        }
    }

    static QStringList parseCsvLine(const QString& line)
    {
        QStringList values;
        QString current;
        bool inQuotes = false;
        for (int index = 0; index < line.size(); ++index) {
            const QChar ch = line.at(index);
            if (ch == QChar('"')) {
                if (inQuotes && index + 1 < line.size() && line.at(index + 1) == QChar('"')) {
                    current.append(QChar('"'));
                    ++index;
                } else {
                    inQuotes = !inQuotes;
                }
            } else if (ch == QChar(',') && !inQuotes) {
                values.append(current);
                current.clear();
            } else {
                current.append(ch);
            }
        }
        values.append(current);
        return values;
    }

