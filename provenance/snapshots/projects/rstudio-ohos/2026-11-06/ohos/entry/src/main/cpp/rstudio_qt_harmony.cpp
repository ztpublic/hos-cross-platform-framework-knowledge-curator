    void refreshGitStatus()
    {
        if (!gitOutput_)
            return;
        const QString nativeStatus = nativeGitStatus(projectPath_);
        if (!nativeStatus.isEmpty()) {
            gitOutput_->setPlainText(nativeStatus);
            qInfo().noquote() << "RStudioQt native git status chars=" << nativeStatus.size();
            return;
        }
        if (findGitRoot(projectPath_).isEmpty()) {
            gitOutput_->setPlainText(QStringLiteral(
                "当前项目中没有找到 Git 仓库。\n\n"
                "项目：%1\n\n"
                "可通过“文件 → 选择项目”打开包含 .git 文件夹的目录。").arg(projectPath_));
            return;
        }
        const QString program = gitProgram();
        if (program.isEmpty()) {
            gitOutput_->setPlainText(QStringLiteral(
                "检测到 .git 目录，但当前 HarmonyOS 运行时未提供 git 可执行文件。"));
            return;
        }
        auto* process = new QProcess(gitOutput_);
        process->setWorkingDirectory(projectPath_);
        connect(process, &QProcess::readyRead, gitOutput_, [process, this]() {
            gitOutput_->setPlainText(QString::fromLocal8Bit(process->readAll()));
        });
        connect(process, &QProcess::errorOccurred, gitOutput_, [this](QProcess::ProcessError) {
            gitOutput_->setPlainText(QStringLiteral("当前 HarmonyOS 运行时未提供 git 可执行文件。"));
        });
        connect(process, QOverload<int, QProcess::ExitStatus>::of(&QProcess::finished), gitOutput_,
                [process, this](int exitCode, QProcess::ExitStatus) {
                    if (exitCode != 0 && gitOutput_->toPlainText().trimmed().isEmpty())
                        gitOutput_->setPlainText(QStringLiteral("git status 执行失败（%1）。").arg(exitCode));
                    process->deleteLater();
                });
        gitOutput_->setPlainText(QStringLiteral("正在读取 Git 状态（%1）…").arg(program));
        process->start(program, QStringList() << QStringLiteral("status") << QStringLiteral("--short"));
    }

