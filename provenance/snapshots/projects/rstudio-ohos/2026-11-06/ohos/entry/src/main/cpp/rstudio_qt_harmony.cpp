    void updateSourceTabLabel(QPlainTextEdit* sourceEditor)
    {
        if (!sourceTabs_ || !sourceEditor)
            return;
        const int index = sourceTabs_->indexOf(sourceEditor);
        if (index < 0)
            return;
        const QString modifiedSuffix = sourceEditor->document()->isModified()
            ? QStringLiteral(" *") : QString();
        sourceTabs_->setTabText(index, sourceTabLabel(sourceEditor->property("sourcePath").toString())
                                 + modifiedSuffix);
    }

