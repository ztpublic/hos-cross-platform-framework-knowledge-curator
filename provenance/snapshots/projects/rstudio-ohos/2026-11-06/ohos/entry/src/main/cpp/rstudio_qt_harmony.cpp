extern "C" int main(int argc, char** argv)
{
    static char appName[] = "rstudio-qt";
    static char* fallbackArgv[] = {appName, nullptr};
    if (argc <= 0 || argv == nullptr) {
        argc = 1;
        argv = fallbackArgv;
    }
    return runRStudioQt(argc, argv);
}

