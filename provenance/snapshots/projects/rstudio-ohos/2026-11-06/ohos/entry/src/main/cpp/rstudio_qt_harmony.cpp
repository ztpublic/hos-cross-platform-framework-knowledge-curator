    void runLocalWorkflowSmoke()
    {
        // Exercise the native source/file/history path without requiring
        // synthetic pointer input on a HarmonyOS desktop device. Restore the
        // editor state before removing the temporary project file.
        const QString smokePath = QDir(projectPath_).filePath(QStringLiteral(".rstudio-ohos-source-smoke.R"));
        const QByteArray sourceText = QByteArrayLiteral("ohos_source_smoke <- 42\n");
        QFile seed(smokePath);
        const bool seeded = seed.open(QIODevice::WriteOnly | QIODevice::Text)
            && seed.write(sourceText) == sourceText.size();
        seed.close();

        QPlainTextEdit* originalEditor = editor_;
        const QString originalPath = currentFile_;
        const QString originalText = originalEditor ? originalEditor->toPlainText() : QString();
        const bool originalModified = originalEditor && originalEditor->document()->isModified();
        const int originalIndex = sourceTabs_ ? sourceTabs_->currentIndex() : -1;
        bool opened = false;
        bool saved = false;
        bool contentsMatch = false;
        bool restored = false;
        if (seeded) {
            openFilePath(smokePath);
            opened = QFileInfo::exists(smokePath)
                && currentFile_ == QFileInfo(smokePath).absoluteFilePath();
            if (opened) {
                editor_->appendPlainText(QStringLiteral("# saved by OpenHarmony source smoke"));
                saved = saveFile();
                QFile verify(smokePath);
                if (verify.open(QIODevice::ReadOnly | QIODevice::Text))
                    contentsMatch = QString::fromUtf8(verify.readAll()).contains(
                        QStringLiteral("saved by OpenHarmony source smoke"));
            }
        }

        if (originalEditor && editor_ == originalEditor) {
            editor_->setPlainText(originalText);
            editor_->setProperty("sourcePath", originalPath);
            editor_->document()->setModified(originalModified);
            currentFile_ = originalPath;
            updateSourceTabLabel(editor_);
            updateSourceTitle();
            restored = true;
        } else if (sourceTabs_ && editor_) {
            const int smokeIndex = sourceTabs_->indexOf(editor_);
            if (smokeIndex >= 0 && sourceTabs_->count() > 1) {
                sourceTabs_->removeTab(smokeIndex);
                editor_->deleteLater();
            }
            if (originalIndex >= 0 && originalIndex < sourceTabs_->count())
                sourceTabs_->setCurrentIndex(originalIndex);
            restored = editor_ == originalEditor || currentFile_ == originalPath;
        }

        const bool fileExists = QFileInfo::exists(smokePath);
        const bool fileModelIndex = fileModel_ && fileModel_->index(smokePath).isValid();
        QFile::remove(smokePath);
        const bool historyVisible = history_ != nullptr;
        qInfo().noquote() << "RStudioQt source workflow smoke seeded=" << (seeded ? 1 : 0)
                          << "opened=" << (opened ? 1 : 0)
                          << "saved=" << (saved ? 1 : 0)
                          << "contentsMatch=" << (contentsMatch ? 1 : 0)
                          << "restored=" << (restored ? 1 : 0);
        qInfo().noquote() << "RStudioQt files workflow smoke exists=" << (fileExists ? 1 : 0)
                          << "modelIndex=" << (fileModelIndex ? 1 : 0);
        qInfo().noquote() << "RStudioQt history workflow smoke visible=" << (historyVisible ? 1 : 0);

        const QString gitSmokeRoot = QDir(QDir::tempPath()).filePath(QStringLiteral("rstudio-ohos-git-smoke"));
        QDir(gitSmokeRoot).removeRecursively();
        const QString gitDir = QDir(gitSmokeRoot).filePath(QStringLiteral(".git"));
        const QString trackedPath = QDir(gitSmokeRoot).filePath(QStringLiteral("tracked.txt"));
        const QByteArray trackedText = QByteArrayLiteral("tracked\n");
        QDir().mkpath(gitDir);
        QFile gitHead(QDir(gitDir).filePath(QStringLiteral("HEAD")));
        gitHead.open(QIODevice::WriteOnly | QIODevice::Text);
        gitHead.write("ref: refs/heads/ohos-smoke\n");
        gitHead.close();
        QFile trackedFile(trackedPath);
        trackedFile.open(QIODevice::WriteOnly | QIODevice::Text);
        trackedFile.write(trackedText);
        trackedFile.close();

        const QByteArray blobHeader = QByteArrayLiteral("blob ")
            + QByteArray::number(trackedText.size()) + QByteArrayLiteral("\0");
        const QByteArray blobHash = QCryptographicHash::hash(blobHeader + trackedText, QCryptographicHash::Sha1);
        QByteArray indexBytes = QByteArrayLiteral("DIRC");
        auto appendBigEndian32 = [](QByteArray& target, quint32 value) {
            target.append(char((value >> 24) & 0xff));
            target.append(char((value >> 16) & 0xff));
            target.append(char((value >> 8) & 0xff));
            target.append(char(value & 0xff));
        };
        auto appendBigEndian16 = [](QByteArray& target, quint16 value) {
            target.append(char((value >> 8) & 0xff));
            target.append(char(value & 0xff));
        };
        appendBigEndian32(indexBytes, 2);
        appendBigEndian32(indexBytes, 1);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, 0100644);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, 0);
        appendBigEndian32(indexBytes, trackedText.size());
        indexBytes.append(blobHash);
        appendBigEndian16(indexBytes, quint16(QStringLiteral("tracked.txt").size()));
        indexBytes.append("tracked.txt", 11);
        indexBytes.append('\0');
        while (indexBytes.size() % 8 != 0)
            indexBytes.append('\0');
        QFile gitIndex(QDir(gitDir).filePath(QStringLiteral("index")));
        gitIndex.open(QIODevice::WriteOnly);
        gitIndex.write(indexBytes);
        gitIndex.close();

        const bool gitClean = nativeGitStatus(gitSmokeRoot).contains(QStringLiteral("工作区干净"));
        trackedFile.open(QIODevice::Append | QIODevice::Text);
        trackedFile.write("changed\n");
        trackedFile.close();
        const bool gitModified = nativeGitStatus(gitSmokeRoot).contains(QStringLiteral(" M  tracked.txt"));
        QFile untrackedFile(QDir(gitSmokeRoot).filePath(QStringLiteral("untracked.txt")));
        untrackedFile.open(QIODevice::WriteOnly | QIODevice::Text);
        untrackedFile.write("untracked\n");
        untrackedFile.close();
        const bool gitUntracked = nativeGitStatus(gitSmokeRoot).contains(QStringLiteral("??  untracked.txt"));
        qInfo().noquote() << "RStudioQt git workflow smoke clean=" << (gitClean ? 1 : 0)
                          << "modified=" << (gitModified ? 1 : 0)
                          << "untracked=" << (gitUntracked ? 1 : 0);
        QDir(gitSmokeRoot).removeRecursively();
    }

    bool writeFile(const QString& path)
    {
        const QString localPath = toInternalAppPath(path);
        QFile file(localPath);
        if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
            showWarningMessage(QStringLiteral("保存失败"), file.errorString());
            return false;
        }
        file.write(editor_->toPlainText().toUtf8());
        const QString absolutePath = normalizedFilePath(localPath);
        editor_->setProperty("sourcePath", absolutePath);
        editor_->document()->setModified(false);
        currentFile_ = absolutePath;
        updateSourceTabLabel(editor_);
        refreshFilesPane();
        statusBar()->showMessage(QStringLiteral("已保存：%1").arg(absolutePath), 3000);
        return true;
    }

    void updateSourceTitle()
    {
        const QString name = currentFile_.isEmpty()
            ? QStringLiteral("未命名") : QFileInfo(currentFile_).fileName();
        const QString modified = (editor_ && editor_->document()->isModified())
            ? QStringLiteral(" *") : QString();
        setWindowTitle(name + modified);
        if (sourcePathLabel_) {
            if (currentFile_.isEmpty()) {
                sourcePathLabel_->setText(QStringLiteral("未命名文件"));
            } else {
                QString relative = QDir(projectPath_).relativeFilePath(currentFile_);
                if (relative.startsWith(QStringLiteral("..")))
                    relative = currentFile_;
                sourcePathLabel_->setText(relative + modified);
            }
        }
        updateSourceWelcome();
    }

