    void newFile()
    {
        // "New" always opens another source tab.  Existing tabs keep their
        // unsaved edits; only an untouched empty Untitled buffer is reused.
        if (currentFile_.isEmpty() && !editor_->document()->isModified()
            && editor_->toPlainText().isEmpty()) {
            editor_->setFocus();
            statusBar()->showMessage(QStringLiteral("已在编辑一个空的未命名文件"), 2500);
            return;
        }

        editor_ = createSourceEditor(QString(), QString());
        const int index = sourceTabs_->addTab(editor_, QStringLiteral("未命名"));
        sourceTabs_->setCurrentIndex(index);
        currentFile_.clear();
        editor_->setFocus();
        updateSourceTitle();
        statusBar()->showMessage(QStringLiteral("已新建文件"), 2500);
    }

