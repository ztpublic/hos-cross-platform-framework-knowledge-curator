// Embedded R writes printed output through the callback table rather than
// returning it from R_ParseEvalString.  The runtime is single-threaded on the
// dedicated R QThread, so a small per-process buffer is sufficient to bridge
// that output back to the Qt console after each evaluation.
QByteArray gEmbeddedRConsoleOutput;

struct RStudioRCommand
{
    QString text;
    bool printResult = true;
};

void writeEmbeddedRConsole(const char* buffer, int length, int outputType)
{
    if (!buffer || length <= 0)
        return;
    gEmbeddedRConsoleOutput.append(buffer, length);
    const QByteArray text = QByteArray(buffer, length).trimmed();
    if (!text.isEmpty())
        qInfo().noquote() << "RStudioQt embedded R console" << outputType
                          << QString::fromLocal8Bit(text);
}

void writeEmbeddedRConsolePlain(const char* buffer, int length)
{
    writeEmbeddedRConsole(buffer, length, 0);
}

struct EmbeddedParseEvalCall
{
    SEXP (*parseEval)(const char*, SEXP) = nullptr;
    const char* code = nullptr;
    SEXP environment = nullptr;
    SEXP result = nullptr;
    // R_ToplevelExec() clears R_Visible during its cleanup, so capture the
    // visibility flag immediately after evaluation while it still describes
    // the user expression (the value an interactive REPL would print).
    Rboolean* visiblePtr = nullptr;
    Rboolean resultVisible = FALSE;
};

void runEmbeddedParseEval(void* opaque)
{
    auto* call = static_cast<EmbeddedParseEvalCall*>(opaque);
    if (call && call->parseEval) {
        call->result = call->parseEval(call->code, call->environment);
        if (call->visiblePtr)
            call->resultVisible = *call->visiblePtr;
    }
}

QString findExecutable(const QString& preferred, const QString& fallback)
{
    if (!preferred.isEmpty() && QFileInfo::exists(preferred))
        return preferred;
    if (QFileInfo(fallback).isAbsolute() && QFileInfo(fallback).isFile())
        return fallback;
    return QStandardPaths::findExecutable(fallback);
}

QString findBundledExecutable(const QString& runtimeRoot, const QString& name)
{
    if (runtimeRoot.isEmpty())
        return QString();

    QStringList candidates;
    if (name == QStringLiteral("R"))
        // The shell wrapper generated by R's configure step contains the
        // build-machine R_HOME.  On HarmonyOS the extracted runtime is
        // relocatable, so invoke the real ELF entry point first and provide
        // R_HOME/LD_LIBRARY_PATH from configureBundledREnvironment().
        candidates << QDir(runtimeRoot).filePath(QStringLiteral("lib/R/bin/exec/R"))
                   << QDir(runtimeRoot).filePath(QStringLiteral("bin/R"));
    candidates << QDir(runtimeRoot).filePath(QStringLiteral("bin/%1").arg(name))
               << QDir(runtimeRoot).filePath(QStringLiteral("%1").arg(name));
    for (const QString& candidate : candidates) {
        const QFileInfo candidateInfo(candidate);
        if (candidateInfo.isFile() && (candidateInfo.isExecutable() || name == QStringLiteral("R")))
            return candidate;
    }
    return QString();
}

QString findBundledRuntimeRoot()
{
    const QString configured = qEnvironmentVariable("RSTUDIO_RUNTIME_ROOT");
    if (!configured.isEmpty() && QDir(configured).exists())
        return QDir(configured).absolutePath();

    const QDir appDir(QCoreApplication::applicationDirPath());
    QStringList candidates;
    candidates << QStringList{
        appDir.absolutePath(),
        appDir.filePath(QStringLiteral("runtime")),
        appDir.filePath(QStringLiteral("../runtime")),
        appDir.filePath(QStringLiteral("../resources/rawfile/runtime")),
        appDir.filePath(QStringLiteral("resources/rawfile/runtime"))
    };
#if defined(Q_OS_OPENHARMONY)
    // EntryAbility extracts rawfiles under the module's files directory;
    // prefer that fresh source over an older QStandardPaths mirror.
    candidates << QStringLiteral("/data/storage/el2/base/haps/entry/files/rstudio-runtime");
#endif
    const QStringList writableLocations = {
        QStandardPaths::writableLocation(QStandardPaths::AppDataLocation),
        QStandardPaths::writableLocation(QStandardPaths::AppLocalDataLocation),
        QStandardPaths::writableLocation(QStandardPaths::GenericDataLocation)
    };
    for (const QString& writableLocation : writableLocations) {
        if (writableLocation.isEmpty())
            continue;
        QDir directory(writableLocation);
        for (int depth = 0; depth < 4; ++depth) {
            candidates << directory.filePath(QStringLiteral("rstudio-runtime"));
            if (!directory.cdUp())
                break;
        }
    }
    for (const QString& candidate : candidates) {
        const QDir runtimeDir(candidate);
        if (!runtimeDir.exists())
            continue;
        if (QFileInfo(runtimeDir.filePath(QStringLiteral("lib/R/library/base/R/base"))).exists())
            return runtimeDir.absolutePath();
    }
    for (const QString& candidate : candidates) {
        if (QDir(candidate).exists())
            return QDir(candidate).absolutePath();
    }
    return QString();
}

bool hasBundledRHome(const QString& runtimeRoot)
{
    return !runtimeRoot.isEmpty()
        && QFileInfo(QDir(runtimeRoot).filePath(QStringLiteral("lib/R/library/base/R/base"))).exists();
}

QString bundledRHome(const QString& runtimeRoot)
{
    return QDir(runtimeRoot).filePath(QStringLiteral("lib/R"));
}

void configureBundledREnvironment(QProcessEnvironment* environment, const QString& runtimeRoot)
{
    if (!environment || !hasBundledRHome(runtimeRoot))
        return;

    const QString rHome = bundledRHome(runtimeRoot);
    const QString rLibraryPath = QDir(rHome).filePath(QStringLiteral("lib"));
    environment->insert(QStringLiteral("R_HOME"), rHome);
    environment->insert(QStringLiteral("R_SHARE_DIR"), QDir(rHome).filePath(QStringLiteral("share")));
    environment->insert(QStringLiteral("R_INCLUDE_DIR"), QDir(rHome).filePath(QStringLiteral("include")));
    environment->insert(QStringLiteral("R_DOC_DIR"), QDir(rHome).filePath(QStringLiteral("doc")));
    environment->insert(QStringLiteral("PATH"),
                        QDir(runtimeRoot).filePath(QStringLiteral("bin"))
                            + QStringLiteral(":") + environment->value(QStringLiteral("PATH")));
    environment->insert(QStringLiteral("LD_LIBRARY_PATH"),
                        rLibraryPath + QStringLiteral(":")
                            + environment->value(QStringLiteral("LD_LIBRARY_PATH")));
}

void prepareBundledRLibraryMirror(const QString& runtimeRoot)
{
    if (!hasBundledRHome(runtimeRoot))
        return;

    const QDir appDir(QCoreApplication::applicationDirPath());
    QDir nativeRoot(appDir.filePath(QStringLiteral("lib/R")));
    if (!QFileInfo::exists(nativeRoot.filePath(QStringLiteral("library/utils/libs/utils.so"))))
        nativeRoot = QDir(appDir.filePath(QStringLiteral("../arm64-v8a/lib/R")));
    const QDir runtimeLibsDir(QDir(runtimeRoot).filePath(QStringLiteral("lib/R/library")));
    const QStringList packages = {
        QStringLiteral("parallel"),
        QStringLiteral("tools"),
        QStringLiteral("methods"),
        QStringLiteral("utils"),
        QStringLiteral("splines"),
        QStringLiteral("grDevices"),
        QStringLiteral("graphics"),
        QStringLiteral("stats"),
        QStringLiteral("grid")
    };

    for (const QString& packageName : packages) {
        const QString sourceLibrary = nativeRoot.filePath(QStringLiteral("library/%1/libs/%1.so").arg(packageName));
        const QString targetLibrary = runtimeLibsDir.filePath(QStringLiteral("%1/libs/%1.so").arg(packageName));
        if (!QFileInfo(sourceLibrary).exists())
            continue;
        QDir().mkpath(QFileInfo(targetLibrary).absolutePath());
        QFile::remove(targetLibrary);
        if (!QFile::copy(sourceLibrary, targetLibrary))
            qWarning().noquote() << "RStudioQt failed to mirror package DSO" << sourceLibrary
                                 << "->" << targetLibrary;
        else
            QFile::setPermissions(targetLibrary, QFileDevice::ReadOwner | QFileDevice::WriteOwner
                                  | QFileDevice::ExeOwner | QFileDevice::ReadGroup | QFileDevice::ExeGroup
                                  | QFileDevice::ReadOther | QFileDevice::ExeOther);
    }

    const QStringList modules = {
        QStringLiteral("lapack"),
        QStringLiteral("internet")
    };
    for (const QString& moduleName : modules) {
        const QString sourceLibrary = nativeRoot.filePath(QStringLiteral("modules/%1.so").arg(moduleName));
        const QString targetLibrary = QDir(runtimeRoot).filePath(QStringLiteral("lib/R/modules/%1.so").arg(moduleName));
        if (!QFileInfo(sourceLibrary).exists())
            continue;
        QDir().mkpath(QFileInfo(targetLibrary).absolutePath());
        QFile::remove(targetLibrary);
        if (!QFile::copy(sourceLibrary, targetLibrary))
            qWarning().noquote() << "RStudioQt failed to mirror R module" << sourceLibrary
                                 << "->" << targetLibrary;
        else
            QFile::setPermissions(targetLibrary, QFileDevice::ReadOwner | QFileDevice::WriteOwner
                                  | QFileDevice::ExeOwner | QFileDevice::ReadGroup | QFileDevice::ExeGroup
                                  | QFileDevice::ReadOther | QFileDevice::ExeOther);
    }
}

QString mirrorRuntimeForNativeR(const QString& sourceRoot)
{
    if (sourceRoot.isEmpty() || !hasBundledRHome(sourceRoot))
        return QString();

    const QString appDataRoot = QStandardPaths::writableLocation(QStandardPaths::AppDataLocation);
    if (appDataRoot.isEmpty())
        return QString();
    const QString targetRoot = QDir(appDataRoot).filePath(QStringLiteral("rstudio-runtime"));
    const QString markerPath = QDir(targetRoot).filePath(QStringLiteral(".native_runtime_v3"));
    if (QFileInfo::exists(markerPath) && hasBundledRHome(targetRoot))
        return targetRoot;

    if (!QDir().mkpath(targetRoot)) {
        qWarning().noquote() << "RStudioQt failed to create native runtime mirror" << targetRoot;
        return QString();
    }

    int copiedFiles = 0;
    QDirIterator iterator(sourceRoot,
                          QDir::AllEntries | QDir::NoDotAndDotDot,
                          QDirIterator::Subdirectories);
    while (iterator.hasNext()) {
        const QString sourcePath = iterator.next();
        const QFileInfo sourceInfo(sourcePath);
        const QString relativePath = QDir(sourceRoot).relativeFilePath(sourcePath);
        const QString targetPath = QDir(targetRoot).filePath(relativePath);
        if (sourceInfo.isDir()) {
            if (!QDir().mkpath(targetPath)) {
                qWarning().noquote() << "RStudioQt failed to create runtime mirror directory" << targetPath;
                return QString();
            }
            continue;
        }
        const QString targetDirectory = QFileInfo(targetPath).absolutePath();
        if (!QDir().mkpath(targetDirectory)) {
            qWarning().noquote() << "RStudioQt failed to create runtime mirror parent" << targetDirectory;
            return QString();
        }
        const QFileInfo targetInfo(targetPath);
        if (targetInfo.exists() && targetInfo.size() == sourceInfo.size())
            continue;
        QFile::remove(targetPath);
        if (!QFile::copy(sourcePath, targetPath)) {
            qWarning().noquote() << "RStudioQt failed to mirror runtime file" << sourcePath
                                 << "->" << targetPath;
            return QString();
        }
        QFile::setPermissions(targetPath, sourceInfo.permissions());
        ++copiedFiles;
    }

    QFile marker(markerPath);
    if (!marker.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        qWarning().noquote() << "RStudioQt failed to write native runtime mirror marker" << markerPath;
        return QString();
    }
    marker.write("r-console-native-mirror-v3\n");
    marker.close();
    qInfo().noquote() << "RStudioQt native runtime mirror ready" << targetRoot
                      << "copiedFiles=" << copiedFiles;
    return targetRoot;
}

