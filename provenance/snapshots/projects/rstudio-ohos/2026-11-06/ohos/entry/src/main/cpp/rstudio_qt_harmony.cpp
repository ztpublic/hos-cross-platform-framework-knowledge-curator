    void onRCommandCompleted(const QString& command, const QString& output, int exitCode)
    {
        QString panel;
        auto panelIterator = panelForCommand_.find(command);
        if (panelIterator != panelForCommand_.end() && !panelIterator.value().isEmpty()) {
            panel = panelIterator.value().dequeue();
            if (panelIterator.value().isEmpty())
                panelForCommand_.erase(panelIterator);
        }

        if (panel == QStringLiteral("environment")) {
            environmentRefreshPending_ = false;
            populateEnvironmentTable(output);
        } else if (panel == QStringLiteral("packages")) {
            packages_->clear();
            const QStringList packageLines = output.split(QRegularExpression(QStringLiteral("[\\r\\n]+")),
                                                          Qt::SkipEmptyParts);
            for (const QString& packageLine : packageLines) {
                const QStringList parts = packageLine.split(QLatin1Char('\t'));
                const QString name = parts.value(0).trimmed();
                if (name.isEmpty())
                    continue;
                const QString version = parts.value(1).trimmed();
                packages_->addItem(version.isEmpty() ? name : QStringLiteral("%1  %2").arg(name, version));
            }
            if (packageCountLabel_)
                packageCountLabel_->setText(QStringLiteral("%1 个程序包（内置 + 用户库）").arg(packages_->count()));
        } else if (panel == QStringLiteral("help")) {
            QString helpText = output.trimmed();
            const int firstTag = helpText.indexOf(QLatin1Char('<'));
            if (firstTag > 0 && firstTag <= 64
                && helpText.contains(QStringLiteral("<html"), Qt::CaseInsensitive))
                helpText = helpText.mid(firstTag);
            if (helpText.startsWith(QStringLiteral("<"), Qt::CaseInsensitive)
                || helpText.contains(QStringLiteral("<body"), Qt::CaseInsensitive))
                helpBrowser_->setHtml(helpText);
            else
                helpBrowser_->setPlainText(helpText);
        } else if (panel == QStringLiteral("data")) {
            populateDataTable(output);
            if (exitCode == 0)
                statusBar()->showMessage(QStringLiteral("数据查看器已加载 %1 行").arg(dataTable_->rowCount()), 3000);
        } else if (panel == QStringLiteral("plot")) {
            if (exitCode != 0 && plotView_) {
                plotView_->clearPlot(output.trimmed().isEmpty()
                    ? QStringLiteral("绘图失败，请到控制台查看 R 错误。")
                    : output.trimmed());
            }
        } else if (panel == QStringLiteral("welcome")) {
            if (!output.trimmed().isEmpty()) {
                QString versionLine = output.trimmed();
                versionLine.replace(QStringLiteral("R version "), QStringLiteral("R 版本 "));
                appendConsoleText(versionLine);
                QString rVersion = QStringLiteral("R 4.6.1");
                const QRegularExpression versionPattern(QStringLiteral("R version ([0-9.]+)"));
                const QRegularExpressionMatch versionMatch = versionPattern.match(output);
                if (versionMatch.hasMatch())
                    rVersion = QStringLiteral("R %1").arg(versionMatch.captured(1));
                if (rStatusLabel_)
                    rStatusLabel_->setText(rVersion + QStringLiteral(" · 内置运行时"));
                updateStatusPill(QStringLiteral("● 内置 R 已就绪"), true);
                statusBar()->showMessage(QStringLiteral("内置 R 已就绪"), 3000);
            }
        } else if (panel == QStringLiteral("project")) {
            refreshEnvironment();
            refreshPackages();
            refreshGitStatus();
        } else if (panel == QStringLiteral("selftest")) {
            showSelfTestResults(output);
        }

        // A user console command may have created or changed objects; refresh
        // the Environment pane after the queue settles.
        if (panel.isEmpty() && !environmentRefreshScheduled_) {
            environmentRefreshScheduled_ = true;
            QTimer::singleShot(250, this, [this]() {
                environmentRefreshScheduled_ = false;
                refreshEnvironment();
            });
        }
    }

    void populateEnvironmentTable(const QString& output)
    {
        if (!environmentTable_)
            return;
        const QStringList lines = output.split(QRegularExpression(QStringLiteral("[\\r\\n]+")),
                                               Qt::SkipEmptyParts);
        environmentTable_->setRowCount(0);
        for (const QString& line : lines) {
            const QStringList columns = line.split(QLatin1Char('\t'));
            const QString name = columns.value(0).trimmed();
            if (name.isEmpty() || name == QStringLiteral("正在加载 .GlobalEnv…"))
                continue;
            const int row = environmentTable_->rowCount();
            environmentTable_->insertRow(row);
            environmentTable_->setItem(row, 0, new QTableWidgetItem(name));
            environmentTable_->setItem(row, 1, new QTableWidgetItem(columns.value(1).trimmed()));
            environmentTable_->setItem(row, 2, new QTableWidgetItem(columns.value(2).trimmed()));
            environmentTable_->setItem(row, 3, new QTableWidgetItem(columns.value(3).trimmed()));
        }
        if (environmentStack_) {
            environmentStack_->setCurrentWidget(
                environmentTable_->rowCount() > 0
                    ? static_cast<QWidget*>(environmentTable_) : environmentEmpty_);
        }
        if (lines.isEmpty())
            statusBar()->showMessage(QStringLiteral("环境为空（.GlobalEnv）"), 2000);
    }

