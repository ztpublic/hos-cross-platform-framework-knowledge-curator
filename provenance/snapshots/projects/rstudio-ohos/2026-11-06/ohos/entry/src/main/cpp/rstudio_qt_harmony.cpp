QString toInternalAppPath(const QString& path)
{
    // The HarmonyOS document picker returns the user-visible app-data view
    // (/storage/Users/.../org.rstudio.qt.openharmony/files/...), while Qt,
    // R and the Terminal use the process view
    // (/data/storage/el2/base/files/...).  Map the picker form back so the
    // same file is not opened twice and so R can read it with the same path.
    const QString externalMarker = QStringLiteral(
        "/appdata/el2/base/org.rstudio.qt.openharmony/files");
    const int markerIndex = path.indexOf(externalMarker);
    if (markerIndex >= 0) {
        const QString internalRoot = QStringLiteral("/data/storage/el2/base/files");
        return internalRoot + path.mid(markerIndex + externalMarker.size());
    }
    return path;
}

QString normalizedFilePath(const QString& path)
{
    QString candidate = toInternalAppPath(path);
    if (candidate.startsWith(QStringLiteral("file:"), Qt::CaseInsensitive)) {
        const QString local = QUrl(candidate).toLocalFile();
        if (!local.isEmpty())
            candidate = local;
    }
    const QFileInfo info(candidate);
    const QString canonical = info.canonicalFilePath();
    return canonical.isEmpty() ? info.absoluteFilePath() : canonical;
}

bool sameSourcePath(const QString& left, const QString& right)
{
    if (left.isEmpty() || right.isEmpty())
        return false;
    if (QDir::cleanPath(left) == QDir::cleanPath(right))
        return true;
    const QString normalizedLeft = normalizedFilePath(left);
    const QString normalizedRight = normalizedFilePath(right);
    if (!normalizedLeft.isEmpty() && normalizedLeft == normalizedRight)
        return true;
    const QFileInfo leftInfo(left);
    const QFileInfo rightInfo(right);
    if (leftInfo.exists() && rightInfo.exists()) {
        const QString leftCanonical = leftInfo.canonicalFilePath();
        const QString rightCanonical = rightInfo.canonicalFilePath();
        if (!leftCanonical.isEmpty() && leftCanonical == rightCanonical)
            return true;
        if (leftInfo.absoluteFilePath() == rightInfo.absoluteFilePath())
            return true;
    }
    return false;
}

