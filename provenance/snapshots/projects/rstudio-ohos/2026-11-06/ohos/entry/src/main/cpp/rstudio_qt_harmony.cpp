int runRStudioQt(int argc, char** argv)
{
    qInfo().noquote() << "RStudioQt runRStudioQt entered argc=" << argc;
    QApplication* app = qobject_cast<QApplication*>(QCoreApplication::instance());
    std::unique_ptr<QApplication> ownedApp;
    if (!app) {
        ownedApp.reset(new QApplication(argc, argv));
        app = ownedApp.get();
    }

    QApplication::setApplicationName(QStringLiteral("RStudio Qt"));
    QApplication::setApplicationDisplayName(QStringLiteral("RStudio Qt"));
    QApplication::setOrganizationName(QStringLiteral("RStudio"));
    QApplication::setOrganizationDomain(QStringLiteral("rstudio.org"));
    QApplication::setApplicationVersion(QStringLiteral("ohos-qt-0.1"));
    QApplication::setQuitOnLastWindowClosed(true);

    QApplication::setApplicationDisplayName(QStringLiteral("RStudio 鸿蒙版"));
    auto* chineseTranslator = new ChineseUiTranslator(app);
    app->installTranslator(chineseTranslator);
    app->setStyle(QStringLiteral("Fusion"));
    QFont appFont = QFontDatabase::systemFont(QFontDatabase::GeneralFont);
    appFont.setPointSizeF(15.5);
    appFont.setStyleStrategy(QFont::PreferAntialias);
    app->setFont(appFont);
    app->setStyleSheet(applicationStyleSheet());

    QString projectPath;
    for (int i = 1; i < argc; ++i) {
        const QString argument = QString::fromLocal8Bit(argv[i]);
        if (argument == QStringLiteral("--project") && i + 1 < argc)
            projectPath = QString::fromLocal8Bit(argv[++i]);
        else if (!argument.startsWith(QLatin1Char('-')))
            projectPath = argument;
    }

    auto runtime = std::make_unique<RStudioSessionRuntime>();
    RStudioMainWindow window(runtime.get(), projectPath);
    qInfo().noquote() << "RStudioQt RStudioMainWindow created projectPath=" << projectPath;
#if defined(Q_OS_OPENHARMONY)
    auto* helper = new QOhWidgetHelper(&window, &window);
    helper->setSupportedWindowModes(QOhWidgetHelper::FULL_SCREEN |
                                    QOhWidgetHelper::SPLIT |
                                    QOhWidgetHelper::FLOATING);
    // Keep the normal HarmonyOS window decoration so the system title bar
    // provides minimize/maximize/close and the user can resize the window.
    helper->setWindowDecorVisible(true);
    helper->setWindowTitleMoveEnabled(true);
    helper->setWindowRectAutoSave(false);
    window.setWindowFlags(window.windowFlags()
                          | Qt::WindowMinMaxButtonsHint
                          | Qt::WindowCloseButtonHint);
    window.setMinimumSize(1800, 1100);
    window.resize(2400, 1500);
    if (QScreen* screen = QGuiApplication::primaryScreen()) {
        const QRect available = screen->availableGeometry();
        window.move(available.center() - QPoint(window.width() / 2, window.height() / 2));
    }
    window.show();
    window.raise();
    window.activateWindow();
    qInfo().noquote() << "RStudioQt window.show normal state="
                      << static_cast<int>(window.windowState())
                      << "geometry=" << window.geometry().width()
                      << "x" << window.geometry().height();
#else
    window.resize(1440, 900);
    window.show();
#endif
    qInfo() << "RStudioQt runRStudioQt exit path ownedApp=" << (ownedApp ? 1 : 0);
    const int exitCode = ownedApp ? app->exec() : 0;
    runtime.reset();
    return exitCode;
}

